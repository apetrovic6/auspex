// Everything under `entities/` is regenerated wholesale by sea-orm-cli, so the workspace's
// pedantic lint set has nothing to offer it: any fix would have to be made in the generator
// and would be overwritten on the next run. Same reasoning as `crates/proto`.
//
// The allowance lives *here*, on the declaration, and not inside `entities/mod.rs` where it
// reads more naturally — because `just services/api/entities` rewrites that file, this one
// being outside its `--output-dir`. Written there it is lost the first time the schema
// changes, and what comes back is `empty_enums` on every generated `pub enum Relation {}`
// and a failing `just check` with no obvious fix. An `allow` on a module declaration covers
// the whole module tree beneath it, so nothing is given up by moving it.
#[allow(
    clippy::pedantic,
    clippy::nursery,
    reason = "generated by sea-orm-cli; fixes would be overwritten"
)]
pub mod entities;
pub mod health;
pub mod migrations;
pub mod startup;
