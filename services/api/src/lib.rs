//! Connect RPC API service.
//!
//! Everything lives in the library target rather than in `main.rs`, so that the
//! integration tests under `tests/` can reach it: a test binary links the *library*, and
//! a module declared only in `main.rs` is invisible to it. `main.rs` stays a thin wrapper
//! that parses arguments and calls in here.
//!
//! Those modules must NOT also be declared in `main.rs` — that compiles each of them a
//! second time into the binary as a separate, incompatible set of types.
//!
//! # Layout
//!
//! Features are vertical slices: `health/`, and later one directory per feature, each
//! owning its own domain types, errors and service implementation. Service impls are
//! versioned to match their proto package (`service/v1.rs`), so a `v2` lands beside `v1`
//! rather than replacing it. [`startup::register_services`] is the one place that knows
//! the whole set.

/// Where the Connect services are mounted. Re-exported so callers can say
/// `api::API_PREFIX` without depending on `proto` directly.
pub use proto::API_PREFIX;

/// The service's timeout budget.
///
/// These are one setting in three places, and the ORDER is the point:
///
/// ```text
/// readiness probe  <  database acquire  <  request timeout
/// ```
///
/// Whichever deadline fires first decides what the client sees. If the request timeout
/// fires first, every database outage becomes an empty `408 Request Timeout` — no Connect
/// error code, no message, nothing to act on — instead of an `internal` error naming the
/// failure, or a readiness response naming the component that is down. Both of those
/// regressions were observed before these were pulled into one place.
///
/// Change one and the assertions below will tell you if the ordering broke.
pub mod timeouts {
    use std::time::Duration;

    /// Outer deadline for any request.
    pub const REQUEST: Duration = Duration::from_secs(5);
    /// How long a handler waits for a pooled connection.
    pub const DB_ACQUIRE: Duration = Duration::from_secs(3);
    /// How long the readiness probe waits on a dependency.
    pub const READINESS_PROBE: Duration = Duration::from_secs(2);

    const _: () = assert!(
        READINESS_PROBE.as_secs() < DB_ACQUIRE.as_secs(),
        "readiness must answer before the pool gives up, or it cannot report which \
         component failed"
    );
    const _: () = assert!(
        DB_ACQUIRE.as_secs() < REQUEST.as_secs(),
        "the pool must fail before the request deadline, or a database outage is reported \
         as an empty 408 instead of an `internal` Connect error"
    );
}

