//! The field vocabulary the API generators share.
//!
//! Every generator in this module family writes code that has to agree about one thing:
//! what a field *is*. The migration spells it as a `ColumnDef`, the contract as a proto
//! field, the entity as a struct member, and the four conversion impls move a value
//! between all three. Those are four spellings of one fact, and a generator that derived
//! each independently would be the repository's favourite defect — a rule applied in one
//! place and not another — shipped by the tool meant to prevent it.
//!
//! So there is one [`Field`], and each spelling is a method on it.
//!
//! # Where fields come from
//!
//! Three sources, in decreasing order of authority:
//!
//! 1. **An existing entity** (`src/entities/<table>.rs`). Generated by sea-orm-cli from the
//!    live schema, so it is the only source that describes what the database actually has.
//! 2. **An existing `.proto`**, for growing a slice that already exists.
//! 3. **`--field name:type` on the command line**, for the first run, before either exists.
//!
//! All three land in the same `Vec<Field>`, which is what keeps the generated conversions
//! consistent whichever way the generator was invoked.

use anyhow::{Context as _, Result, bail};

use crate::repo;

/// The types a generated field may have.
///
/// Deliberately small. These are the proto scalars that map cleanly onto both a Postgres
/// column and a Rust type without a decision — the set a first version of a feature is
/// written in. Anything outside it (a timestamp, an enum, a nested message) is a design
/// choice with more than one defensible answer, and the generator's job is to get the
/// boilerplate out of the way, not to make that choice silently. [`FieldType::Message`]
/// exists only because parsing an *existing* proto will meet one, and a parser that
/// skipped the field would generate a conversion that quietly drops data.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum FieldType {
    String,
    Bool,
    Int32,
    Int64,
    Double,
    Bytes,
    /// A nested message, by the type name the contract gives it.
    ///
    /// Carried rather than rejected so the generated conversion can name what it could not
    /// write. A message field is also what makes a request conversion *fallible*: buffa
    /// represents one as a `MessageField`, which may be unset, and deciding what an unset
    /// one means is the author's call.
    Message(String),
}

impl FieldType {
    /// Parse the type half of a `--field name:type` specification.
    fn parse(word: &str) -> Result<Self> {
        Ok(match word {
            "string" | "text" => Self::String,
            "bool" | "boolean" => Self::Bool,
            "int32" | "int" | "i32" => Self::Int32,
            "int64" | "bigint" | "i64" => Self::Int64,
            "double" | "float" | "f64" => Self::Double,
            "bytes" | "blob" => Self::Bytes,
            other => bail!(
                "unknown field type {other:?} — known types are string, bool, int32, \
                 int64, double, bytes. A timestamp, an enum or a nested message is a \
                 design decision rather than a default, so it is added by hand after the \
                 skeleton is in place."
            ),
        })
    }

    /// How the contract spells it.
    pub const fn proto(&self) -> &str {
        match self {
            Self::String => "string",
            Self::Bool => "bool",
            Self::Int32 => "int32",
            Self::Int64 => "int64",
            Self::Double => "double",
            Self::Bytes => "bytes",
            Self::Message(name) => name.as_str(),
        }
    }

    /// How a domain struct spells it.
    ///
    /// A message field has no domain spelling the generator can invent — the domain type
    /// for a nested message is the thing the author is being asked to write — so it
    /// returns the proto type name and the caller leaves a `TODO` beside it.
    pub const fn rust(&self) -> &str {
        match self {
            Self::String => "String",
            Self::Bool => "bool",
            Self::Int32 => "i32",
            Self::Int64 => "i64",
            Self::Double => "f64",
            Self::Bytes => "Vec<u8>",
            Self::Message(name) => name.as_str(),
        }
    }

    /// The `ColumnDef` builder call for a migration, when this type has a column at all.
    ///
    /// `text()` rather than `string()` for a string: `string` renders as `varchar(255)` on
    /// Postgres, and a length limit nobody chose is a truncation nobody predicted. Postgres
    /// stores both identically, so the limit buys nothing it costs.
    ///
    /// `None` for a message, which has no column of its own — it is a foreign key or a
    /// second table, and which of those it is cannot be read off the contract. An `Option`
    /// rather than a plausible-looking default, because the default would be a column that
    /// silently stores the wrong thing.
    pub const fn column(&self) -> Option<&str> {
        Some(match self {
            Self::String => "text",
            Self::Bool => "boolean",
            Self::Int32 => "integer",
            Self::Int64 => "big_integer",
            Self::Double => "double",
            Self::Bytes => "binary",
            Self::Message(_) => return None,
        })
    }

    /// Whether a value of this type needs unwrapping on the way out of a request.
    pub const fn is_message(&self) -> bool {
        matches!(self, Self::Message(_))
    }
}

/// One field, in the single spelling every generator here reads.
#[derive(Debug, Clone)]
pub struct Field {
    /// `snake_case` — what proto, sea-orm and Rust all call it, so there is nothing to
    /// convert between the three.
    pub name: String,
    pub ty: FieldType,
    /// `repeated` in the contract, `Vec<T>` in Rust. No column of its own.
    pub repeated: bool,
    /// Explicit presence in the contract, `Option<T>` in the entity.
    pub optional: bool,
}

impl Field {
    /// Parse one `--field name:type` specification.
    ///
    /// `name:type?` marks it nullable and `name:type[]` repeated, because the two
    /// alternatives are both worse: a flag per property would make the common case
    /// (`--field name:string`) the verbose one, and a positional triple would be
    /// unreadable at four fields.
    pub fn parse(spec: &str) -> Result<Self> {
        let (name, ty) = spec
            .split_once(':')
            .with_context(|| format!("field {spec:?} must be written `name:type`"))?;

        let name = name.trim();
        if name.is_empty() {
            bail!("field {spec:?} has an empty name");
        }
        if !name
            .chars()
            .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
        {
            bail!(
                "field name {name:?} must be lower-case ASCII, digits and underscores — it \
                 is used verbatim as a proto field, a column and a Rust struct member, and \
                 only that set is legal in all three"
            );
        }
        if name == "id" {
            bail!(
                "field {spec:?} names the primary key, which every generated table, domain \
                 type and contract message already carries. Drop it from the field list."
            );
        }

        let ty = ty.trim();
        let (ty, repeated) = ty.strip_suffix("[]").map_or((ty, false), |t| (t, true));
        let (ty, optional) = ty.strip_suffix('?').map_or((ty, false), |t| (t, true));

        Ok(Self {
            name: name.to_owned(),
            ty: FieldType::parse(ty)?,
            repeated,
            optional,
        })
    }

    /// `PascalCase`, for the `DeriveIden` variant a migration names the column by.
    pub fn pascal(&self) -> String {
        repo::to_pascal(&self.name)
    }

    /// How a domain struct declares it.
    pub fn domain_type(&self) -> String {
        let base = self.ty.rust().to_owned();
        match (self.repeated, self.optional) {
            (true, _) => format!("Vec<{base}>"),
            (false, true) => format!("Option<{base}>"),
            (false, false) => base,
        }
    }
}

/// Parse `--field` specifications, refusing duplicates.
///
/// A repeated name is accepted by every individual parse and produces a struct with two
/// members of the same name, which fails to compile a long way from the typo.
pub fn parse_fields(specs: &[String]) -> Result<Vec<Field>> {
    let mut fields: Vec<Field> = Vec::new();
    for spec in specs {
        let field = Field::parse(spec)?;
        if let Some(existing) = fields.iter().find(|f| f.name == field.name) {
            bail!("field {:?} is given twice", existing.name);
        }
        fields.push(field);
    }
    Ok(fields)
}

/// The table name a feature's rows live in.
///
/// English plurals, badly, on purpose: this is a default a `--table` flag overrides, and
/// the cost of getting it wrong is typing that flag. The alternative — a pluralisation
/// crate — is a dependency and a dictionary for a guess, and sea-orm-cli has already named
/// the table by the time anything downstream reads it.
pub fn pluralize(name: &str) -> String {
    let snake = name.replace('-', "_");
    if snake.ends_with('s')
        || snake.ends_with('x')
        || snake.ends_with('z')
        || snake.ends_with("ch")
        || snake.ends_with("sh")
    {
        return format!("{snake}es");
    }
    match snake.strip_suffix('y') {
        // `city` -> `cities`, but `day` -> `days`: the rule is about a consonant before
        // the y, which is why this is not a bare `ends_with('y')`.
        Some(stem) if !stem.ends_with(['a', 'e', 'i', 'o', 'u']) => format!("{stem}ies"),
        _ => format!("{snake}s"),
    }
}

/// Columns every generated table has, which no generated *field* corresponds to.
///
/// The primary key is handled separately everywhere — a domain type carries it, a write
/// DTO does not — so letting it through here would put it in both. The two stamps are
/// infrastructure: the migration gives them database defaults precisely so that nothing in
/// the service writes them, and a DTO carrying `updated_at` is an invitation to do exactly
/// that from the one place that must not.
const INFRASTRUCTURE_COLUMNS: &[&str] = &[
    "id",
    "created_at",
    "updated_at",
    // What a product that followed `fishing`'s naming has instead.
    "created_at_utc",
    "updated_at_utc",
];

/// What a sea-orm entity's `Model` declares, split the way the generators use it.
#[derive(Debug, Clone)]
pub struct Entity {
    /// The columns a generated conversion moves a value through.
    pub fields: Vec<Field>,
    /// The `INFRASTRUCTURE_COLUMNS` this entity actually has, in declaration order.
    ///
    /// Recorded rather than assumed, because `new-feature --table` can be pointed at an entity
    /// a hand-written migration made. `new-feature` spells each of these as `NotSet` in the
    /// `ActiveModel` it builds, so that a dropped field is E0063 rather than a column silently
    /// left to its default — and a column the entity does not have would be E0560 instead.
    pub infrastructure: Vec<String>,
}

/// Fields read out of a sea-orm entity, and the infrastructure columns it has.
///
/// The entity is generated from the live schema, so this is the one source that cannot be
/// out of date with the database.
///
/// The infrastructure columns are skipped as fields, as they always were, but no longer
/// forgotten: [`Entity::infrastructure`] says which of them this entity declared. One parse
/// rather than a second function reading the same struct, for the reason [`Contract`]
/// gives — a file that parses two ways drifts in the gap between the two readings.
///
/// A deliberately small parser. The input is machine-written by sea-orm-cli with a stable
/// shape (`pub struct Model {` then one `pub <name>: <type>,` per line), not arbitrary
/// Rust, and a real parse would mean a syn dependency in a tool whose whole point is to
/// run before anything else compiles.
///
/// The body ends at a line that is exactly `}`. Every line inside it has to be blank, a
/// `//` comment, part of an attribute, or a `pub <name>: <type>,` declaration; anything
/// else is refused and quoted. Skipping an unreadable line would generate a conversion
/// that silently drops a column, and `pub(crate) name: String,` is exactly such a line.
///
/// Attributes are tracked by bracket depth rather than by their first line, because
/// sea-orm-cli formats its output and a long `#[sea_orm(…)]` can wrap onto continuation
/// lines that begin with neither `#` nor `pub`. A `}` inside an attribute string is not
/// the end of the struct for the same reason.
pub fn fields_from_entity(source: &str) -> Result<Entity> {
    let body = source
        .split_once("pub struct Model {")
        .map(|(_, rest)| rest)
        .context("the entity has no `pub struct Model {` — is it a sea-orm entity?")?;

    // Find the closing brace first, so that a struct with no close is reported as such
    // rather than as the `pub enum Relation` that follows it being an unreadable field.
    let mut attribute_depth = 0;
    let mut closed = false;
    for line in body.lines() {
        let line = line.trim();
        if attribute_depth > 0 {
            attribute_depth = attribute_bracket_depth(line, attribute_depth);
        } else if line.starts_with("#[") {
            attribute_depth = attribute_bracket_depth(line, 0);
        } else if line == "}" {
            closed = true;
            break;
        }
    }
    if !closed {
        bail!("the entity's `Model` struct is not closed");
    }

    let mut fields = Vec::new();
    let mut infrastructure = Vec::new();
    let mut attribute_depth = 0;
    for line in body.lines() {
        let line = line.trim();
        if attribute_depth > 0 {
            attribute_depth = attribute_bracket_depth(line, attribute_depth);
            continue;
        }
        if line.starts_with("#[") {
            attribute_depth = attribute_bracket_depth(line, 0);
            continue;
        }
        if line == "}" {
            break;
        }
        if line.is_empty() || line.starts_with("//") {
            continue;
        }

        let (name, ty) = field_declaration(line)?;
        if INFRASTRUCTURE_COLUMNS.contains(&name) {
            infrastructure.push(name.to_owned());
            continue;
        }

        let ty = ty.trim();
        let (ty, optional) = ty
            .strip_prefix("Option<")
            .and_then(|inner| inner.strip_suffix('>'))
            .map_or((ty, false), |inner| (inner.trim(), true));
        let (ty, repeated) = match ty.strip_prefix("Vec<").and_then(|t| t.strip_suffix('>')) {
            // `Vec<u8>` is a bytes column, not a repeated field. The distinction matters:
            // one is a column, the other is a second table.
            Some(inner) if inner.trim() != "u8" => (inner.trim(), true),
            _ => (ty, false),
        };

        let ty = match ty {
            "String" => FieldType::String,
            "bool" => FieldType::Bool,
            "i32" => FieldType::Int32,
            "i64" => FieldType::Int64,
            "f64" | "f32" => FieldType::Double,
            "Vec<u8>" => FieldType::Bytes,
            other => bail!(
                "entity field `{name}: {other}` has a type these generators do not map to \
                 the contract. Add the field to the .proto and the conversions by hand — \
                 and leave the rest to the generator by passing `--field` for the ones it \
                 does understand."
            ),
        };

        fields.push(Field {
            name: name.to_owned(),
            ty,
            repeated,
            optional,
        });
    }

    if fields.is_empty() {
        bail!(
            "the entity's `Model` struct has no columns besides the primary key and the \
             timestamps"
        );
    }
    Ok(Entity {
        fields,
        infrastructure,
    })
}

/// The name and type of one `pub <name>: <type>,` line, or an error quoting the line.
///
/// Every `pub` line inside `Model` is one of these; anything else is refused rather than
/// skipped, for the reason [`fields_from_entity`] gives. `pub(crate) name: String,` reaches
/// the first branch because it does not start with `pub `.
fn field_declaration(line: &str) -> Result<(&str, &str)> {
    let Some(declaration) = line.strip_prefix("pub ") else {
        bail!(
            "the entity's `Model` contains a line these generators cannot read: `{line}`. \
             Only a field declaration (`pub <name>: <type>,`), an attribute, a comment \
             and a blank line belong inside the struct — refusing rather than skipping \
             it, because a skipped line is a column the generated conversion would drop."
        );
    };
    let (name, ty) = declaration
        .trim()
        .strip_suffix(',')
        .and_then(|declaration| declaration.split_once(':'))
        .map(|(name, ty)| (name.trim(), ty.trim()))
        .with_context(|| {
            format!(
                "the entity's `Model` contains a `pub` line that is not a field \
                 declaration (`pub <name>: <type>,`): `{line}`"
            )
        })?;
    if !is_identifier(name) {
        bail!(
            "the entity's `Model` contains a `pub` line whose name is not an \
             identifier: `{line}`"
        );
    }
    Ok((name, ty))
}

/// Bracket depth of one line of an attribute, ignoring brackets inside string literals.
///
/// `depth` is what the previous line left open; zero means the attribute's matching `]`
/// has been read and the next line is ordinary struct content again.
fn attribute_bracket_depth(line: &str, mut depth: usize) -> usize {
    let mut in_string = false;
    let mut escaped = false;
    for ch in line.chars() {
        if in_string {
            if escaped {
                escaped = false;
            } else if ch == '\\' {
                escaped = true;
            } else if ch == '"' {
                in_string = false;
            }
            continue;
        }
        match ch {
            '"' => in_string = true,
            '[' => depth += 1,
            ']' => depth = depth.saturating_sub(1),
            _ => {}
        }
    }
    depth
}

/// Whether a field name is a Rust identifier (optionally a raw one).
///
/// sea-orm-cli emits raw identifiers for column names that are keywords, so `r#type` has
/// to stay readable even though it is not a bare identifier.
fn is_identifier(name: &str) -> bool {
    let name = name.strip_prefix("r#").unwrap_or(name);
    let mut chars = name.chars();
    matches!(chars.next(), Some(first) if first == '_' || first.is_ascii_alphabetic())
        && chars.all(|ch| ch == '_' || ch.is_ascii_alphanumeric())
}

/// One message parsed out of a `.proto`.
#[derive(Debug, Clone)]
pub struct Message {
    pub name: String,
    pub fields: Vec<Field>,
}

/// One `rpc` declaration, as the `service` block spells it.
///
/// The request and response are the type *names*, not the messages themselves: a method may
/// name a message from another file, and resolving imports is a job for buf rather than for
/// this. [`Contract::message`] is how a caller that needs the fields looks one up.
#[derive(Debug, Clone)]
pub struct Rpc {
    pub name: String,
    pub request: String,
    pub response: String,
}

/// One `service` block.
#[derive(Debug, Clone)]
pub struct Service {
    pub name: String,
    pub rpcs: Vec<Rpc>,
}

/// Everything this parser reads out of one `.proto`.
///
/// The service half exists for `new-rpc`, which has to refuse a method the contract already
/// declares — and could only do that by reading the `service` block, which until RT-23 no
/// parser here could see. One parser rather than a second one reading the same file: a file
/// that parses two ways drifts in the gap between the two readings.
#[derive(Debug, Clone, Default)]
pub struct Contract {
    pub messages: Vec<Message>,
    pub services: Vec<Service>,
}

impl Contract {
    /// The message of that name, if the file declares one.
    pub fn message(&self, name: &str) -> Option<&Message> {
        self.messages.iter().find(|message| message.name == name)
    }

    /// The service block that already declares `rpc`, if any does.
    ///
    /// Returned rather than a bool so a refusal can name the block the method is already in,
    /// which is the thing the reader then has to go and look at.
    pub fn declares(&self, rpc: &str) -> Option<(&Service, &Rpc)> {
        self.services.iter().find_map(|service| {
            service
                .rpcs
                .iter()
                .find(|declared| declared.name == rpc)
                .map(|declared| (service, declared))
        })
    }
}

/// Parse the messages and services out of a proto3 file.
///
/// Enough of proto3 to read a contract this repository generates or a person writes in the
/// same shape: `message X { <label> <type> <name> = <n>; }` and
/// `service S { rpc M(Req) returns (Resp); }`, with `//` and `/* */` comments and nested
/// braces skipped. Not a validator — buf lint is, and it runs in CI — so anything it does
/// not recognise inside a body is ignored rather than rejected.
///
/// Why hand-rolled: the alternatives are a protobuf parser crate (a dependency added to a
/// build-time tool for one file format) or shelling out to `buf` (which needs the network
/// for its plugins and is exactly what `cargo build` is kept independent of). The grammar
/// actually needed here is a dozen lines.
pub fn parse_proto(source: &str) -> Contract {
    let text = strip_comments(source);
    let mut contract = Contract::default();
    let mut rest = text.as_str();

    while let Some(block) = next_block(rest) {
        if !block.name.is_empty() {
            match block.keyword {
                "message" => contract.messages.push(Message {
                    name: block.name,
                    fields: parse_message_fields(block.body),
                }),
                _ => contract.services.push(Service {
                    name: block.name,
                    rpcs: parse_rpcs(block.body),
                }),
            }
        }
        rest = block.rest;
    }

    contract
}

/// One top-level declaration and what follows it.
struct Block<'a> {
    keyword: &'static str,
    name: String,
    body: &'a str,
    rest: &'a str,
}

/// The next `message` or `service` declaration, whichever comes first.
///
/// Nested declarations are stepped over rather than read, because `rest` resumes past the
/// whole body — which is what keeps a nested `message Inner` out of the top-level list.
fn next_block(text: &str) -> Option<Block<'_>> {
    let (keyword, at) = ["message", "service"]
        .into_iter()
        .filter_map(|keyword| declaration_at(text, keyword).map(|at| (keyword, at)))
        .min_by_key(|&(_, at)| at)?;

    let after = &text[at + keyword.len()..];
    let brace = after.find('{')?;
    let body_start = brace + 1;
    let body_len = balanced_body(&after[body_start..])?;

    Some(Block {
        keyword,
        name: after[..brace].trim().to_owned(),
        body: &after[body_start..body_start + body_len],
        rest: &after[body_start + body_len..],
    })
}

/// Offset of `keyword` where it opens a line, or `None`.
///
/// At the start of a line, rather than anywhere: `string service = 1;` contains the word
/// `service` and declares nothing, and a parser that took it for a block would read the
/// name of whatever followed. Every contract this repository writes, and everything buf
/// format produces, puts a declaration at the start of its own line.
fn declaration_at(text: &str, keyword: &str) -> Option<usize> {
    let mut offset = 0;
    for line in text.lines() {
        let indent = line.len() - line.trim_start().len();
        if let Some(rest) = line[indent..].strip_prefix(keyword)
            && rest.starts_with(char::is_whitespace)
        {
            return Some(offset + indent);
        }
        offset += line.len() + 1;
    }
    None
}

/// The `rpc` declarations of one `service` body.
///
/// Whitespace-normalised before anything else, so a declaration buf has broken over three
/// lines reads the same as one on a single line. An rpc this missed would be an rpc
/// `new-rpc` declared a *second* time, which is the one refusal that generator owes its
/// caller.
fn parse_rpcs(body: &str) -> Vec<Rpc> {
    let flat = body.split_whitespace().collect::<Vec<_>>().join(" ");
    let mut rpcs = Vec::new();

    for statement in flat.split("rpc ").skip(1) {
        let Some((name, rest)) = statement.split_once('(') else {
            continue;
        };
        let Some((request, rest)) = rest.split_once(')') else {
            continue;
        };
        let Some(rest) = rest.trim_start().strip_prefix("returns") else {
            continue;
        };
        let Some((_, rest)) = rest.split_once('(') else {
            continue;
        };
        let Some((response, _)) = rest.split_once(')') else {
            continue;
        };

        let name = name.trim();
        if name.is_empty()
            || !name
                .chars()
                .all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '.')
        {
            continue;
        }

        rpcs.push(Rpc {
            name: name.to_owned(),
            request: message_type(request),
            response: message_type(response),
        });
    }

    rpcs
}

/// One side of an rpc, without the `stream` label a streaming method carries.
fn message_type(side: &str) -> String {
    let side = side.trim();
    side.strip_prefix("stream ")
        .unwrap_or(side)
        .trim()
        .to_owned()
}

/// The fields of one message body, ignoring nested messages and anything unrecognised.
fn parse_message_fields(body: &str) -> Vec<Field> {
    let mut fields = Vec::new();
    let mut depth = 0_usize;

    for statement in body.split(';') {
        // A nested message or enum opens a brace that `split(';')` does not respect, so
        // statements inside one are tracked and skipped rather than read as fields.
        depth += statement.matches('{').count();
        depth = depth.saturating_sub(statement.matches('}').count());
        if depth > 0 {
            continue;
        }

        // The statement that *closes* a nested message carries the closing brace and then
        // the next field: `} bool flag = 2`. Keeping only what follows the last brace is
        // what lets the field after a nested message be seen at all — without it, the
        // parser silently loses one field per nested message, which is the kind of
        // undercount that would make a generated conversion drop a column.
        let statement = statement.rsplit('}').next().unwrap_or(statement);
        let statement = statement.trim();
        let Some((declaration, _number)) = statement.split_once('=') else {
            continue;
        };
        let mut words: Vec<&str> = declaration.split_whitespace().collect();
        if words.is_empty() {
            continue;
        }

        let mut repeated = false;
        let mut optional = false;
        while let Some(first) = words.first() {
            match *first {
                "repeated" => repeated = true,
                "optional" => optional = true,
                _ => break,
            }
            words.remove(0);
        }

        // What is left must be exactly `<type> <name>`. `reserved 3;`, `option (x) = y;`
        // and anything else fails this and is skipped.
        let [ty, name] = words[..] else {
            continue;
        };
        let ty = match ty {
            "string" => FieldType::String,
            "bool" => FieldType::Bool,
            "int32" | "uint32" | "sint32" | "fixed32" => FieldType::Int32,
            "int64" | "uint64" | "sint64" | "fixed64" => FieldType::Int64,
            "double" | "float" => FieldType::Double,
            "bytes" => FieldType::Bytes,
            other => FieldType::Message(other.to_owned()),
        };

        fields.push(Field {
            name: name.to_owned(),
            ty,
            repeated,
            optional,
        });
    }

    fields
}

/// Length of the balanced body starting just inside an opening brace.
fn balanced_body(text: &str) -> Option<usize> {
    let mut depth = 1_usize;
    for (index, character) in text.char_indices() {
        match character {
            '{' => depth += 1,
            '}' => {
                depth -= 1;
                if depth == 0 {
                    return Some(index);
                }
            }
            _ => {}
        }
    }
    None
}

/// Replace comments with spaces, preserving every byte offset around them.
///
/// Spaces rather than deletion so a `//` comment cannot join the line below it to the line
/// above, which would turn two statements into one unparsable one.
fn strip_comments(source: &str) -> String {
    let bytes = source.as_bytes();
    let mut out = String::with_capacity(source.len());
    let mut index = 0;

    while index < bytes.len() {
        if bytes[index..].starts_with(b"//") {
            while index < bytes.len() && bytes[index] != b'\n' {
                out.push(' ');
                index += 1;
            }
        } else if bytes[index..].starts_with(b"/*") {
            let end = source[index..]
                .find("*/")
                .map_or(bytes.len(), |o| index + o + 2);
            for _ in index..end {
                out.push(' ');
            }
            index = end;
        } else {
            // Pushed by character rather than by byte so a multi-byte character in a
            // comment-free stretch survives intact.
            let character = source[index..].chars().next().unwrap_or('\0');
            out.push(character);
            index += character.len_utf8();
        }
    }

    out
}

#[cfg(test)]
