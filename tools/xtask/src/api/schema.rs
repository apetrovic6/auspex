    #[test]
    fn proto_messages_and_their_fields_parse() {
        let proto = r#"
            syntax = "proto3";
            package lake.v1;

            // A lake, with a comment containing message Decoy { string no = 1; }
            message Lake {
              int32 id = 1;
              string name = 2;
              repeated string tags = 3;
              optional string note = 4;
              Position position = 5;
            }

            message ListLakesRequest {}

            service LakeService {
              rpc ListLakes(ListLakesRequest) returns (ListLakesResponse);
            }
        "#;

        let contract = parse_proto(proto);
        let names: Vec<&str> = contract.messages.iter().map(|m| m.name.as_str()).collect();
        assert_eq!(
            names,
            ["Lake", "ListLakesRequest"],
            "the decoy is in a comment"
        );

        let lake = &contract.messages[0];
        assert_eq!(lake.fields.len(), 5);
        assert!(lake.fields[2].repeated);
        assert!(lake.fields[3].optional);
        assert_eq!(
            lake.fields[4].ty,
            FieldType::Message("Position".to_owned()),
            "an unknown type name is a message, not a skipped field"
        );
    }

