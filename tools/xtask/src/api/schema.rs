    #[test]
    fn the_service_block_and_its_rpcs_parse() {
        // What `new-rpc` reads before it writes: the block it has to splice into, and the
        // names it must refuse to declare twice.
        let proto = r#"
            syntax = "proto3";
            package lake.v1;

            message GetLakeRequest {}

            // rpc Decoy(DecoyRequest) returns (DecoyResponse);
            service LakeService {
              rpc GetLake(GetLakeRequest) returns (GetLakeResponse);
              rpc WatchLakes(WatchLakesRequest) returns (stream WatchLakesResponse);
            }
        "#;

        let contract = parse_proto(proto);
        assert_eq!(contract.services.len(), 1);
        let service = &contract.services[0];
        assert_eq!(service.name, "LakeService");

        let names: Vec<&str> = service.rpcs.iter().map(|rpc| rpc.name.as_str()).collect();
        assert_eq!(
            names,
            ["GetLake", "WatchLakes"],
            "the decoy is in a comment"
        );
        assert_eq!(service.rpcs[0].request, "GetLakeRequest");
        assert_eq!(service.rpcs[0].response, "GetLakeResponse");
        // The label is not part of the type name, or a duplicate check would miss it.
        assert_eq!(service.rpcs[1].response, "WatchLakesResponse");

        assert!(contract.declares("GetLake").is_some());
        assert!(
            contract.declares("GetLakes").is_none(),
            "a prefix is not a match"
        );
        assert!(contract.message("GetLakeRequest").is_some());
    }

    #[test]
    fn an_rpc_broken_over_lines_is_still_one_rpc() {
        // buf format wraps a long declaration, and an rpc this parser could not see is an
        // rpc `new-rpc` would declare a second time — the one refusal it owes its caller.
        let proto = "service LakeService {\n\
                     \x20 rpc ArchiveLakeForGoodAndAll(\n\
                     \x20     ArchiveLakeForGoodAndAllRequest) returns (\n\
                     \x20     ArchiveLakeForGoodAndAllResponse);\n\
                     }\n";
        let contract = parse_proto(proto);
        let rpc = &contract.services[0].rpcs[0];
        assert_eq!(rpc.name, "ArchiveLakeForGoodAndAll");
        assert_eq!(rpc.request, "ArchiveLakeForGoodAndAllRequest");
        assert_eq!(rpc.response, "ArchiveLakeForGoodAndAllResponse");
    }

    #[test]
    fn a_field_called_service_does_not_open_a_block() {
        // `service` is a legal field name, and reading it as a declaration would take the
        // name of whatever came next — so the keyword only counts at the start of a line.
        let proto = "message Booking {\n  string service = 1;\n}\n";
        let contract = parse_proto(proto);
        assert!(contract.services.is_empty(), "{:?}", contract.services);
        assert_eq!(contract.messages[0].fields[0].name, "service");
    }
