    #[test]
    fn field_specifications_parse() {
        let field = Field::parse("name:string").expect("a plain field");
        assert_eq!(field.name, "name");
        assert_eq!(field.ty, FieldType::String);
        assert!(!field.repeated && !field.optional);

        let field = Field::parse("tags:string[]").expect("a repeated field");
        assert!(field.repeated);
        assert_eq!(field.domain_type(), "Vec<String>");

        let field = Field::parse("note:string?").expect("an optional field");
        assert!(field.optional);
        assert_eq!(field.domain_type(), "Option<String>");
    }

    #[test]
    fn a_field_called_id_is_refused() {
        // Every generated table, domain type and message carries a primary key already, so
        // accepting this would produce two `id` members and fail a long way from the typo.
        let error = Field::parse("id:int32").expect_err("id must be refused");
        assert!(error.to_string().contains("primary key"), "{error}");
    }

    #[test]
    fn duplicate_fields_are_refused() {
        let specs = ["name:string".to_owned(), "name:bool".to_owned()];
        let error = parse_fields(&specs).expect_err("a duplicate must be refused");
        assert!(error.to_string().contains("twice"), "{error}");
    }

    #[test]
    fn plurals_are_right_often_enough() {
        assert_eq!(pluralize("lake"), "lakes");
        assert_eq!(pluralize("box"), "boxes");
        assert_eq!(pluralize("city"), "cities");
        assert_eq!(pluralize("day"), "days");
        // A word that is already plural comes back wrong, which is the documented limit of
        // this function rather than a bug in it — `--table` is how such a name is given.
        // Asserted as an inequality because writing the wrong plural out in full is a typo
        // as far as `just typos` is concerned, and it would be right.
        assert_ne!(pluralize("series"), "series");
    }

