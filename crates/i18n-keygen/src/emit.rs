//! Turning the locale tree into Rust source.
//!
//! Everything here is string formatting on purpose. The output is `include!`d
//! into the consuming crate, so it has to be readable when a compile error
//! points at it, and `quote!` would cost a syn/proc-macro2 build for a file
//! that has no syntax to analyse.

use std::collections::BTreeMap;

use crate::Generator;
use crate::resources::Entry;

pub fn generate(
    config: &Generator,
    entries: &[Entry],
    // The fallback locale's messages, for the doc comments. `entries` deliberately does
    // not carry the copy: a plural family has several copies and picking one to show is a
    // decision the entry type should not make on a caller's behalf.
    canonical: &BTreeMap<String, String>,
    locales: &[String],
) -> String {
    let mut source = format!(
        r#"// @generated by i18n-keygen from {dir}/. DO NOT EDIT.

/// The locale whose keys are canonical, and the one `i18n!` falls back to.
pub const FALLBACK_LOCALE: &str = "{fallback}";

{keys}
{locales}
"#,
        dir = config.locales_dir.display(),
        fallback = config.fallback,
        keys = generate_keys(entries, canonical, config.doc_comments),
        locales = generate_locales(locales, &config.fallback),
    );

    source.push_str(FALLBACK_ASSERT);

    if config.path_helpers {
        source.push('\n');
        source.push_str(PATH_MODULE);
    }

    if config.translate_wrappers {
        source.push('\n');
        source.push_str(&generate_translate(&config.crate_name));
    }

    source
}

fn generate_keys(
    entries: &[Entry],
    canonical: &BTreeMap<String, String>,
    doc_comments: bool,
) -> String {
    let variants = entries
        .iter()
        .map(|entry| match entry {
            Entry::String(key) => {
                let doc = if doc_comments {
                    canonical.get(key).map_or_else(String::new, |text| {
                        format!("    /// \"{}\"\n    ///\n", doc_text(text))
                    })
                } else {
                    String::new()
                };

                format!("{doc}    /// `{key}`\n    {},", variant_name(key))
            }
            Entry::Plural { family, members } => {
                // The trap this variant creates, stated where it is created: naming a
                // family compiles and renders nothing, because `apples` is not a key and
                // `translate` falls back to its own argument.
                let variant = variant_name(family);

                let mut doc = vec![format!(
                    "    /// `{family}` is a plural family, not a string."
                )];

                if doc_comments {
                    doc.push("    /// Its categories, as the fallback spells them:".to_owned());

                    for member in members {
                        if let Some(text) = canonical.get(member) {
                            doc.push(format!("    /// - `{member}`: `{}`", doc_text(text)));
                        }
                    }
                }

                doc.push("    ///".to_owned());
                doc.push(format!(
                    "    /// Name it with `i18n::plural_key(Key::{variant}, count, locale)`."
                ));
                doc.push(format!(
                    "    /// Naming this variant alone renders the key: there is no key `{family}`."
                ));

                format!("{}\n    {},", doc.join("\n"), variant)
            }
        })
        .collect::<Vec<_>>()
        .join("\n");

    let arms = entries
        .iter()
        .map(|entry| {
            format!(
                "            Self::{} => \"{}\",",
                variant_name(entry.name()),
                entry.name()
            )
        })
        .collect::<Vec<_>>()
        .join("\n");

    let all = entries
        .iter()
        .map(|entry| format!("Self::{}", variant_name(entry.name())))
        .collect::<Vec<_>>()
        .join(", ");

    let catalog = entries
        .iter()
        .flat_map(Entry::catalog)
        .map(|(key, family)| format!("(\"{key}\", \"{family}\")"))
        .collect::<Vec<_>>()
        .join(", ");

    let families = entries
        .iter()
        .filter(|entry| entry.is_plural())
        .map(|entry| format!("\"{}\"", entry.name()))
        .collect::<Vec<_>>()
        .join(", ");

    format!(
        r"/// Every translation key that exists, as a type.
///
/// Naming a key that is not in the locale files is a compile error, and a key
/// added to them shows up here on the next build.
///
/// A plural family is one variant, named for the family: `apples.one` and
/// `apples.other` are `Key::Apples`, because two languages do not have the same
/// number of them and a variant per category would be a different set of
/// variants per build (ADR 0018). `as_str` answers with the family; the strings
/// the locale files actually hold are in [`Key::CATALOG`].
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Key {{
{variants}
}}

impl Key {{
    /// Every key, in file order. Useful for a translation-coverage test.
    pub const ALL: &'static [Self] = &[{all}];

    /// `(key as the locale files spell it, the `Key` that names it)` for every
    /// key any locale defines, sorted.
    ///
    /// This, not [`Key::ALL`], is what enumerates translations: a plural family is
    /// one variant but several strings, and `apples.few` exists in Croatian while
    /// `Key::Apples::as_str()` answers `apples`. A driver that iterated
    /// `Key::ALL` and looked each name up would silently emit no plural at all.
    pub const CATALOG: &'static [(&'static str, &'static str)] = &[{catalog}];

    /// The plural families, by name, so `apples.other` can be enumerated without
    /// knowing which categories exist.
    pub const PLURAL_FAMILIES: &'static [&'static str] = &[{families}];

    #[must_use]
    pub const fn as_str(self) -> &'static str {{
        match self {{
{arms}
        }}
    }}
}}

impl AsRef<str> for Key {{
    fn as_ref(&self) -> &str {{
        self.as_str()
    }}
}}

impl std::fmt::Display for Key {{
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {{
        f.write_str(self.as_str())
    }}
}}
"
    )
}

fn generate_locales(locales: &[String], fallback_locale: &str) -> String {
    let variants = locales
        .iter()
        .map(|locale| format!("    /// `{locale}`\n    {},", variant_name(locale)))
        .collect::<Vec<_>>()
        .join("\n");

    let arms = locales
        .iter()
        .map(|locale| {
            format!(
                "            Self::{} => \"{locale}\",",
                variant_name(locale)
            )
        })
        .collect::<Vec<_>>()
        .join("\n");

    let from_arms = locales
        .iter()
        .map(|locale| {
            format!(
                "            \"{locale}\" => Ok(Self::{}),",
                variant_name(locale)
            )
        })
        .collect::<Vec<_>>()
        .join("\n");

    let all = locales
        .iter()
        .map(|locale| format!("Self::{}", variant_name(locale)))
        .collect::<Vec<_>>()
        .join(", ");

    let fallback = variant_name(fallback_locale);

    format!(
        r#"/// Every locale that has translation files, as a type.
///
/// Generated rather than hand-written so it cannot drift from the files: a
/// locale the picker offers is by construction one `Locale` can represent, and
/// adding `de.toml` is all it takes to get `Locale::De`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Locale {{
{variants}
}}

impl Locale {{
    /// Every locale, sorted by code. This is what a language picker offers.
    pub const ALL: &'static [Self] = &[{all}];

    /// The locale `i18n!` falls back to, and the sensible default.
    pub const FALLBACK: Self = Self::{fallback};

    /// The locale code, as rust-i18n keys its tables — always lowercase, so a
    /// lookup cannot miss the way an uppercased variant name would.
    #[must_use]
    pub const fn as_str(self) -> &'static str {{
        match self {{
{arms}
        }}
    }}
}}

impl AsRef<str> for Locale {{
    fn as_ref(&self) -> &str {{
        self.as_str()
    }}
}}

impl std::fmt::Display for Locale {{
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {{
        f.write_str(self.as_str())
    }}
}}

/// The locale code was not one of the [`Locale::ALL`].
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct UnsupportedLocale;

impl std::fmt::Display for UnsupportedLocale {{
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {{
        f.write_str("unsupported locale")
    }}
}}

impl std::error::Error for UnsupportedLocale {{}}

impl TryFrom<&str> for Locale {{
    type Error = UnsupportedLocale;

    fn try_from(value: &str) -> Result<Self, Self::Error> {{
        match value {{
{from_arms}
            _ => Err(UnsupportedLocale),
        }}
    }}
}}

impl std::str::FromStr for Locale {{
    type Err = UnsupportedLocale;

    fn from_str(value: &str) -> Result<Self, Self::Err> {{
        Self::try_from(value)
    }}
}}
"#
    )
}

/// The fallback locale's copy, fit for a `///` line.
///
/// A message may span lines, and a doc comment may not, so whitespace is
/// collapsed. Square brackets are escaped because rustdoc reads `[foo]` as an
/// intra-doc link and warns when it resolves to nothing — which any ordinary
/// sentence containing brackets otherwise would.
fn doc_text(text: &str) -> String {
    text.split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
        .replace('[', "\\[")
        .replace(']', "\\]")
}

/// `messages.hello_world` -> `MessagesHelloWorld`, `zh-CN` -> `ZhCN`.
///
/// Public because the rule has a second reader: xtask's
/// `translate_with_arguments_match_the_catalog` invariant maps a call site's
/// `Key::CountIs` back to the catalog key that generated it, and a second
/// implementation of this function is a drift waiting to happen.
#[must_use]
pub fn variant_name(key: &str) -> String {
    key.split(['.', '_', '-'])
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut chars = part.chars();
            chars.next().map_or_else(String::new, |first| {
                first.to_uppercase().collect::<String>() + chars.as_str()
            })
        })
        .collect()
}

/// The two halves of the fallback locale, checked against each other.
///
/// These are plain string constants rather than `format!` templates because
/// they interpolate nothing: `format!` would mean doubling every brace in a
/// `macro_rules!` body, which is a transcription error waiting to happen.
const FALLBACK_ASSERT: &str = r#"/// `i18n!` needs its fallback as a literal, so a build script cannot hand it
/// over: the locale code is written twice, once for this generator and once in
/// the `i18n!` call. rust-i18n keeps its own copy in a `static`, which const
/// evaluation may not read, so the two cannot be compared here — what is
/// checked is that the pair generated from the configured fallback agrees, the
/// constant against the variant the locale table resolved it to. A genuine
/// disagreement with `i18n!` shows up at runtime instead, as every missing
/// translation rendering its key.
const _: () = assert!(
    str_eq(FALLBACK_LOCALE, Locale::FALLBACK.as_str()),
    "the generated FALLBACK_LOCALE and Locale::FALLBACK disagree"
);

/// `==` on `&str` is not const, so the comparison is spelled out.
const fn str_eq(a: &str, b: &str) -> bool {
    let (a, b) = (a.as_bytes(), b.as_bytes());

    if a.len() != b.len() {
        return false;
    }

    let mut i = 0;
    while i < a.len() {
        if a[i] != b[i] {
            return false;
        }
        i += 1;
    }

    true
}
"#;

const PATH_MODULE: &str = r#"/// URL paths for locale-prefixed routing.
///
/// [`Locale::FALLBACK`] is unprefixed — `/login` is Croatian, `/en/login` is
/// English — so there is exactly one canonical URL per page per locale.
///
/// This is pure string work and lives here rather than in the frontend: what a
/// localized path looks like is a property of the locale set, and it is far
/// easier to test without a router attached.
pub mod path {
    use super::Locale;


    /// Splits a leading locale segment off a path.
    ///
    /// Returns `(None, path)` unchanged when the first segment is not a locale,
    /// which is how `/lakes` is told apart from `/en/lakes` — the router cannot
    /// do it, because `:locale` matches any segment at all.
    #[must_use]
    pub fn split(path: &str) -> (Option<Locale>, &str) {
        let trimmed = path.strip_prefix('/').unwrap_or(path);

        let (head, tail) = trimmed
            .find('/')
            .map_or((trimmed, ""), |slash| (&trimmed[..slash], &trimmed[slash..]));

        match Locale::try_from(head) {
            Ok(locale) if tail.is_empty() => (Some(locale), "/"),
            Ok(locale) => (Some(locale), tail),
            Err(_) => (None, path),
        }
    }

    /// The locale a path is prefixed with, or [`Locale::FALLBACK`].
    #[must_use]
    pub fn locale_of(path: &str) -> Locale {
        split(path).0.unwrap_or(Locale::FALLBACK)
    }

    /// The same page in `locale`: swaps the prefix, adds one, or drops it.
    ///
    /// `("/en/lakes", Hr)` -> `/lakes`, `("/lakes", En)` -> `/en/lakes`.
    #[must_use]
    pub fn with_locale(path: &str, locale: Locale) -> String {
        let (_, rest) = split(path);

        if locale == Locale::FALLBACK {
            return if rest.is_empty() {
                "/".to_owned()
            } else {
                rest.to_owned()
            };
        }

        match rest {
            "" | "/" => format!("/{locale}"),
            rest => format!("/{locale}{rest}"),
        }
    }
}
"#;

/// The runtime wrappers, whose doctest has to name the crate it lands in.
fn generate_translate(crate_name: &str) -> String {
    format!("{TRANSLATE_HEAD}{crate_name}{TRANSLATE_TAIL}")
}

const TRANSLATE_HEAD: &str = r#"/// The translation for `key` in `locale`, falling back to
/// [`FALLBACK_LOCALE`] and then to the key itself.
///
/// Takes the locale explicitly rather than reading the global one, so a caller
/// driving it from a signal — a reactive UI adapter — gets a value that
/// actually changes when that signal does.
#[must_use]
pub fn translate(key: impl AsRef<str>, locale: impl AsRef<str>) -> String {
    // The path form rather than a bare `t!`: both expand to the same
    // `crate::_rust_i18n_t!`, but this one does not require the consuming crate
    // to have written `#[macro_use] extern crate rust_i18n`.
    rust_i18n::t!(key.as_ref(), locale = locale.as_ref()).to_string()
}

/// The translation for `key` in `locale`, or `None` when that locale does not
/// define it.
///
/// [`translate`] cannot answer this: a missing key falls back to another locale
/// and finally to the key text, and a translation is allowed to equal its key
/// (`lakes = "lakes"` in English), so neither the result nor a comparison
/// against the key distinguishes the two. This asks the backend directly.
#[must_use]
pub fn try_translate(key: impl AsRef<str>, locale: impl AsRef<str>) -> Option<String> {
    // `Backend` is already in scope: `i18n!` expands to a `use rust_i18n::
    // {Backend as _, ...}` at the consuming crate's root, which is where this
    // file is `include!`d.
    _rust_i18n_backend()
        .translate(locale.as_ref(), key.as_ref())
        .map(std::borrow::Cow::into_owned)
}

/// The locale codes that have translation files.
///
/// [`Locale::ALL`] is the typed equivalent and is usually what you want; this
/// exists for callers that need the raw strings, and as the crate-boundary
/// replacement for `available_locales!()`.
#[must_use]
pub fn available_locales() -> Vec<&'static str> {
    Locale::ALL.iter().map(|locale| locale.as_str()).collect()
}

/// The translation for `key` in `locale`, with its `%{name}` placeholders
/// filled in.
///
/// ```
/// # use "#;

const TRANSLATE_TAIL: &str = r#"::{translate_with, Locale};
/// translate_with!("Pozdrav, %{name}", Locale::FALLBACK, name = "Ana");
/// translate_with!("Broj %{sn}", Locale::FALLBACK, sn = 123 => "{:08}");
/// ```
///
/// A macro rather than a function so an argument can be anything that
/// implements [`Display`](std::fmt::Display) rather than only `&str`, and so
/// `=> "{:08}"` can carry a format specifier — `format!` needs its format
/// string as a literal, which only survives as a macro argument. The specifier
/// decorates a `Display` value; it is not a way to reach `Debug`.
///
/// This exists because rust-i18n's own `t!` cannot be used from another crate:
/// it expands to `crate::_rust_i18n_t!`, which `i18n!` defines as
/// `pub(crate)`. Placeholder syntax matches `t!`'s so the locale files read the
/// same either way.
#[macro_export]
macro_rules! translate_with {
    ($key:expr, $locale:expr $(, $name:ident = $value:expr $(=> $spec:literal)?)* $(,)?) => {{
        // Nothing to replace when no arguments were given.
        #[allow(unused_mut)]
        let mut text = $crate::translate($key, $locale);

        $({
            let value = $value;

            // A `macro_rules!` arm cannot branch on an *absent* optional
            // fragment, so the plain `{}` is written unconditionally and a
            // `=> "{:08}"` shadows it. A second macro would read better, and
            // is what this used to be — but a `#[macro_export]` macro defined
            // by `include!` counts as macro-expanded, and reaching one through
            // `$crate::` is a hard error.
            #[allow(unused_variables)]
            let formatted = ::std::format!("{}", value);
            $(let formatted = ::std::format!($spec, value);)?

            text = text.replace(
                ::std::concat!("%{", ::std::stringify!($name), "}"),
                &formatted,
            );
        })*

        text
    }};
}
"#;

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn variant_names_are_upper_camel() {
        assert_eq!(variant_name("messages.hello_world"), "MessagesHelloWorld");
        assert_eq!(variant_name("zh-CN"), "ZhCN");
        assert_eq!(variant_name("hr"), "Hr");
        assert_eq!(
            variant_name("login.errors.email_taken"),
            "LoginErrorsEmailTaken"
        );

        // Empty segments cannot contribute a variant, and must not panic.
        assert_eq!(variant_name("a..b"), "AB");
        assert_eq!(variant_name(""), "");
    }

    #[test]
    fn doc_text_fits_on_one_line() {
        assert_eq!(doc_text("two\nlines"), "two lines");
        assert_eq!(
            doc_text("  padded \t and   squeezed  "),
            "padded and squeezed"
        );
    }

    /// rustdoc reads `[foo]` as an intra-doc link and warns when it resolves to
    /// nothing, so a message that merely mentions brackets would break the
    /// build it was generated into.
    #[test]
    fn doc_text_escapes_brackets() {
        assert_eq!(doc_text("see [the docs]"), "see \\[the docs\\]");
    }
}
